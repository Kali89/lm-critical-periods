#!/usr/bin/env python
"""Export an lmcp run/config as a nanoGPT (karpathy/nanoGPT) config.py + README.md + window_patch.md.

  python3 tools/export_nanogpt.py runs/<run_dir>            [--out exports/nanogpt/<name>]
  python3 tools/export_nanogpt.py configs/grid/x.yaml       (base.yaml is layered underneath)

Needs only PyYAML. Design-level replication, not bit-level: see the generated README.md.
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from lmcp.config import load_config, run_name  # noqa: E402  (pure python + yaml)

PATCH = '''# window_patch.md: corruption window for nanoGPT's train.py

nanoGPT's `get_batch` reads one memmapped token file at random offsets. A corruption window needs two
files and a switch on the iteration fraction. Put both streams in the dataset dir:

    data/<dataset>/train.bin           clean stream   (data/tok/.../train.clean.bin)
    data/<dataset>/train_corrupt.bin   corrupted      (data/tok/.../train.<kind>.bin)
    data/<dataset>/val.bin             clean val      (always clean)

Both must come from the same documents in the same order, so that fraction-of-corpus lines up, as in lmcp.
(Our `bin/lmcp tok encode --kind ...` builds the corrupted stream; copy it over.)

## Sketch (edit train.py)

```python
# near the config block
corrupt_window = {window}      # (start_frac, end_frac) of max_iters, or None

# in get_batch(split), replace the memmap line:
def get_batch(split):
    if split == 'train':
        frac = iter_num / max_iters                     # iter_num is a global in train.py
        in_win = corrupt_window is not None and corrupt_window[0] <= frac < corrupt_window[1]
        fname = 'train_corrupt.bin' if in_win else 'train.bin'
    else:
        fname = 'val.bin'
    data = np.memmap(os.path.join(data_dir, fname), dtype=np.uint16, mode='r')
    ...  # rest unchanged
```

`iter_num` is read at call time, so the switch needs no other plumbing. Evaluation (`estimate_loss`) calls
`get_batch('val')`, which stays clean.

## Things the patch does not fix

- nanoGPT samples uniformly random offsets, so "fraction of the budget" is by iteration, not by corpus
  position. Our window is by iteration too, so these agree; but there is no document order.
- Offsets cross document boundaries (our packing does too, with EOS between docs).
- Schedule: nanoGPT only has warmup + cosine. For `const` set `decay_lr = False`. For `wsd` replace `get_lr`:

```python
def get_lr(it):
    if it < warmup_iters:
        return learning_rate * (it + 1) / warmup_iters
    decay_start = int(max_iters * (1 - decay_frac))   # decay_frac = 0.15 in lmcp
    if it < decay_start:
        return learning_rate
    return learning_rate - (learning_rate - min_lr) * (it - decay_start) / max(1, max_iters - decay_start)
```

Faster alternative: **modded-nanogpt** (github.com/KellerJordan/modded-nanogpt) trains the same GPT-2-scale
setup much faster on GPUs, with RoPE-style/ReLU^2 changes closer to our architecture. The same two-file
window switch applies to its data loader (swap the shard list by iteration fraction).
'''

README = '''# nanoGPT export: {name}

Generated by `tools/export_nanogpt.py` from `{src}`.

## Setup

1. Clone https://github.com/karpathy/nanoGPT.
2. Our token streams are already nanoGPT format (flat uint16 arrays, EOS between docs). Link them in:

       mkdir -p nanoGPT/data/{dataset}
       ln -s {stream_dir}/train.clean.bin nanoGPT/data/{dataset}/train.bin
       ln -s {stream_dir}/val.clean.bin   nanoGPT/data/{dataset}/val.bin
       python3 -c "import pickle; pickle.dump({{'vocab_size': {vocab}}}, open('nanoGPT/data/{dataset}/meta.pkl','wb'))"

   `meta.pkl` makes nanoGPT use `vocab_size={vocab}` instead of the GPT-2 default (it reads it in train.py when present).
   For a corruption arm also link the corrupted stream as `train_corrupt.bin` (see window_patch.md).
3. Copy `config.py` to `nanoGPT/config/` and run `python train.py config/{name}.py`
   (add `--device=mps` / `--compile=False` on a Mac; the config sets `compile = False`).

## Fidelity: this is a design-level replication, not a bit-level one

- nanoGPT samples **random offsets** into the stream: no document order, no epoch structure. Ours steps
  through the stream sequentially. Corrupted streams keep their sentence/doc structure only through the
  token file, which random offsets read the same way.
- nanoGPT has **no corruption window**. Stock train.py reads one file for the whole run. See `window_patch.md`.
- Architecture mismatch: nanoGPT uses **learned positions + GELU + LayerNorm (bias optional)**; ours is RoPE +
  SwiGLU + RMSNorm, no biases. `n_embd`/`n_layer`/`n_head` match; parameter count will differ ({n_params:,} ours,
  nanoGPT will be somewhat larger because of the position table and 4x GELU MLP vs our SwiGLU hidden size).
- Optimizer: lmcp uses MLX AdamW defaults (betas 0.9/0.999); config.py sets beta2 = 0.999 to match (nanoGPT's own default is 0.95).
- LR schedule: {sched_note}
- Batch: {batch_tokens:,} tokens per step = batch_size {batch_size} x block_size {block}, no gradient accumulation.

Faster alternative for GPU runs: modded-nanogpt (github.com/KellerJordan/modded-nanogpt).
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("src", help="run dir or config.yaml")
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    src = Path(a.src)
    if src.is_dir():
        j = json.loads((src / "config.json").read_text())
        cfg = j["config"]
        name = src.name
    else:
        cfg = load_config(src)
        name = run_name(cfg, cfg.get("run", {}).get("grid"))
    out = Path(a.out) if a.out else ROOT / "exports" / "nanogpt" / name
    out.mkdir(parents=True, exist_ok=True)

    d, m, tr, c = cfg["data"], cfg["model"], cfg["train"], cfg["corruption"]
    block = d["seq_len"]
    batch_size = tr["batch_tokens"] // block
    batch_tokens = batch_size * block
    max_iters = tr["tokens"] // batch_tokens
    warmup = max(1, int(max_iters * tr["warmup_frac"]))
    sched = tr["schedule"]
    dataset = f"{d['corpus']}_{d['variant']}_v{d['tokenizer_vocab']}"
    stream = ROOT / "data" / "tok" / dataset
    n_params = json.loads((src / "config.json").read_text())["info"]["n_params"] if src.is_dir() else 0
    window = c.get("window")
    if c["kind"] != "clean" and window is None:
        window = [0.0, 1.0]
    notes = {"const": "const -> decay_lr = False, exact match.",
             "cosine": "cosine -> nanoGPT's native schedule (lr_decay_iters = max_iters, min_lr = lr * min_lr_frac); warmup is linear in both.",
             "wsd": "wsd is NOT native to nanoGPT; decay_lr is set True here but gives cosine unless you swap get_lr (sketch in window_patch.md)."}

    cfgpy = f'''# nanoGPT config generated by tools/export_nanogpt.py from {src}
# corruption: kind={c["kind"]} param={c.get("param")} window={window} (window needs the train.py patch, see window_patch.md)
# lmcp schedule: {sched}. {notes[sched]}
out_dir = 'out-{name}'
eval_interval = {max(1, int(tr["tokens"] // 20 // batch_tokens))}
eval_iters = 50
log_interval = {max(1, tr["log_every"])}
always_save_checkpoint = True
wandb_log = False

dataset = '{dataset}'      # data/{dataset}/{{train.bin,val.bin,meta.pkl}}; meta.pkl gives vocab_size = {d["tokenizer_vocab"]}
gradient_accumulation_steps = 1
batch_size = {batch_size}
block_size = {block}

n_layer = {m["n_layer"]}
n_head = {m["n_head"]}
n_embd = {m["d_model"]}
dropout = 0.0
bias = False

learning_rate = {tr["lr"]}
max_iters = {max_iters}            # tokens {tr["tokens"]:,} // batch_tokens {batch_tokens:,}
weight_decay = {tr["weight_decay"]}
beta1 = 0.9
beta2 = 0.999              # lmcp uses mlx AdamW defaults (0.9, 0.999, eps 1e-8); nanoGPT's own default is 0.95
grad_clip = {tr["grad_clip"]}

decay_lr = {sched != "const"}
warmup_iters = {warmup}
lr_decay_iters = {max_iters}
min_lr = {tr["lr"] * tr["min_lr_frac"]}

compile = False            # torch.compile is unreliable on MPS
# device = 'mps'           # uncomment on a Mac
# lmcp seed was {tr["seed"]}; nanoGPT hardcodes torch.manual_seed(1337 + seed_offset)
'''
    (out / "config.py").write_text(cfgpy)
    (out / "README.md").write_text(README.format(
        name=name, src=src, dataset=dataset, stream_dir=stream, vocab=d["tokenizer_vocab"], n_params=n_params,
        sched_note=notes[sched], batch_tokens=batch_tokens, batch_size=batch_size, block=block))
    (out / "window_patch.md").write_text(PATCH.replace("{window}", repr(tuple(window)) if window else "None"))
    print(out)


if __name__ == "__main__":
    main()
